# შექმენით ფუნქცია. შექმენით რიცხვებით სავსე სია. დათვალეთ თუ რამდენჯერ არის შემდეგი რიცხვი წინაზე მეტი. 
# მაგალითად: თუ მოცემული გვაქვს სია [1, 3, 2, 5, 4],
# მაშინ უნდა დავპრინტოთ 2, რადგან 3 > 1, და 5 > 2. გამოიყენე ინდექსები. გამოიძახეთ ფუნქცია.
def newlist():
    lst1 = [1, 3, 2, 5, 4]  
    count = 0
    for i in range(1, len(lst1)): 
        if lst1[i] > lst1[i-1]:  
            count += 1
    print(count)
newlist()